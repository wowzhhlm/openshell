const F = require('./src/session-format.js');
const xs = '[Connection]\r\nName=Prod\r\nHost=192.168.1.10\r\nPort=22\r\n[SSH]\r\nUser=admin\r\nAuthMethod=PublicKey\r\nUserKeyFile=C:\\keys\\id_rsa\r\n';
const sc = '[S:BE-web]\r\nS:"Hostname"=10.0.0.11\r\nD:"[SSH2] Port"=00000016\r\nS:"Username"=deploy\r\nS:"Protocol Name"=SSH2\r\nS:"Session Name"=BE-web\r\n';
const xj = '<Session name="xml-srv"><Host>1.2.3.4</Host><Port>2222</Port><UserName>root</UserName><AuthMethod>Password</AuthMethod></Session>';
const r1 = F.parseFile({ name: 'prod.xsh', text: xs, group: '生产' });
const r2 = F.parseFile({ name: 'web.ini', text: sc, group: '机房' });
const r3 = F.parseFile({ name: 's.xsh', text: xj, group: '' });
function assert(cond, msg) { if (!cond) { console.error('FAIL: ' + msg); process.exitCode = 1; } else console.log('PASS: ' + msg); }
assert(r1.format === 'xshell-ini', 'Xshell INI 格式识别');
assert(r1.sessions[0] && r1.sessions[0].host === '192.168.1.10', 'Xshell INI 主机解析');
assert(r1.sessions[0] && r1.sessions[0].auth === 'privatekey', 'Xshell 公钥认证识别');
assert(r1.sessions[0] && r1.sessions[0].keyfile.indexOf('id_rsa') > 0, 'Xshell 私钥路径解析');
assert(r2.format === 'securecrt', 'SecureCRT 格式识别');
assert(r2.sessions[0] && r2.sessions[0].port === 22, 'SecureCRT 十六进制端口转换 00000016 -> 22');
assert(r2.sessions[0] && r2.sessions[0].user === 'deploy', 'SecureCRT 用户名解析');
assert(r3.format === 'xshell-xml', 'Xshell XML 格式识别');
assert(r3.sessions[0] && r3.sessions[0].host === '1.2.3.4', 'Xshell XML 主机解析');
assert(r3.sessions[0] && r3.sessions[0].port === 2222, 'Xshell XML 端口解析');
const outX = F.toXshell(r1.sessions[0]);
const outS = F.toSecureCrt(r1.sessions[0]);
assert(outX.name.endsWith('.xsh') && outX.content.includes('Host=192.168.1.10'), 'Xshell 导出内容');
assert(outS.name.endsWith('.ini') && outS.content.includes('D:"[SSH2] Port"=00000016'), 'SecureCRT 导出内容');
assert(!outX.content.includes('Password=admin') && !outS.content.includes('Password V2=secret'), '导出不含明文密码');
const telnetXsh = '[Connection]\r\nName=Router\r\nHost=10.0.0.1\r\nPort=23\r\nProtocol=2\r\n[Telnet]\r\nUser=admin\r\n';
const telnetCrt = '[S:Switch]\r\nS:"Hostname"=10.0.0.2\r\nD:"[Telnet] Port"=00000017\r\nS:"Username"=admin\r\nS:"Protocol Name"=Telnet\r\n';
const rt = F.parseFile({ name: 'router.xsh', text: telnetXsh });
const rc = F.parseFile({ name: 'switch.ini', text: telnetCrt });
assert(rt.sessions[0] && rt.sessions[0].protocol === 'telnet', 'Xshell Telnet 协议识别');
assert(rt.sessions[0] && rt.sessions[0].port === 23, 'Xshell Telnet 端口解析');
assert(rc.sessions[0] && rc.sessions[0].protocol === 'telnet', 'SecureCRT Telnet 协议识别');
assert(rc.sessions[0] && rc.sessions[0].port === 23, 'SecureCRT Telnet 端口 00000017 -> 23');
const outJson = F.toOpenShell([{ ...rt.sessions[0], protocol: 'telnet' }]);
assert(JSON.parse(outJson.content)[0].protocol === 'telnet', 'OpenShell JSON 保留协议字段');
const outTelnet = F.toSecureCrt({ ...rt.sessions[0], protocol: 'telnet' });
assert(outTelnet.content.includes('S:"Protocol Name"=Telnet'), 'SecureCRT 导出写入 Telnet 协议');
console.log('FORMAT_TESTS_DONE');
